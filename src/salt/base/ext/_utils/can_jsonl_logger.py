"""
Contains handling of JSONL logging files, based on the CSV writer from python-can version 3.3.5
"""
from __future__ import absolute_import

from base64 import b64encode, b64decode
from datetime import datetime
import json
import logging
import time

from can.message import Message
from can.listener import Listener
from can.io.generic import BaseIOHandler

logger = logging.getLogger("can.io.jsonl")

class JSONLWriter(BaseIOHandler, Listener):
    """Writes each message as a JSON object.
    """

    def __init__(self, file, append=False):
        """
        :param file: a path-like object or a file-like object to write to.
                     If this is a file-like object, is has to open in text
                     write mode, not binary write mode.
        :param bool append: if set to `True` messages are appended to
                            the file and no header line is written, else
                            the file is truncated and starts with a newly
                            written header line
        """
        mode = 'a' if append else 'w'
        super(JSONLWriter, self).__init__(file, mode=mode)

    def on_message_received(self, msg):
        row = {"timestamp": repr(msg.timestamp), "arbitration_id": hex(msg.arbitration_id),"extended": '1' if msg.is_extended_id else '0',"remote": '1' if msg.is_remote_frame else '0',"error": '1' if msg.is_error_frame else '0',"dlc": str(msg.dlc),"data": b64encode(msg.data).decode('utf8')}
        self.file.write(json.dumps(row, separators=(",", ":")))
        self.file.write('\n')

class JSONLReader(BaseIOHandler):
    """Iterator over CAN messages from a .csv file that was
    generated by :class:`~can.CSVWriter` or that uses the same
    format as described there. Assumes that there is a header
    and thus skips the first line.

    Any line separator is accepted.
    """

    def __init__(self, file):
        """
        :param file: a path-like object or as file-like object to read from
                     If this is a file-like object, is has to opened in text
                     read mode, not binary read mode.
        """
        super(JSONLReader, self).__init__(file, mode='r')

    def __iter__(self):
        # skip the header line
        try:
            next(self.file)
        except StopIteration:
            # don't crash on a file with only a header
            return

        for line in self.file:

            timestamp, arbitration_id, extended, remote, error, dlc, data = line.split(',')

            yield Message(
                timestamp=float(timestamp),
                is_remote_frame=(remote == '1'),
                is_extended_id=(extended == '1'),
                is_error_frame=(error == '1'),
                arbitration_id=int(arbitration_id, base=16),
                dlc=int(dlc),
                data=b64decode(data),
            )

        self.stop()
